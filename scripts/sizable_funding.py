"""What funding do the coins that can hold size pay? Capacity and premium on the same table.

A coin "can hold" a clip of `--clip` dollars per leg when that clip is within the participation
cap. Two filters:
    point in time   2% of trailing-30d min(perp ADV, spot ADV) >= clip, at each 8h window end
                    (qr.capacity.adv: completed bars only). No look-ahead.
    snapshot        1% of today's OI >= clip and 2% of min ADV >= clip, from
                    data/processed/binance/oi_snapshot_<date>.csv (scripts/fetch_oi_snapshot.py).
                    Selects on the present; shown only as a cross-check.
Funding is per fixed 8h window (qr.data.funding.per_window); the default is 0.0001 per window.
Funding only: no costs, no basis.

    python scripts/sizable_funding.py                      # $2.5m per leg, 2025-01-01 on
    python scripts/sizable_funding.py --clip 1e6 --since 2023-01-01

Writes reports/carry/sizable_funding.md.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from qr.capacity import adv
from qr.data.funding import WINDOWS_PER_YEAR, has_spot, load_funding, per_window
from qr.data.prices import load_kline_matrix

START, END = "2023-01-01", "2026-10-23"
DEFAULT, EPS = 0.0001, 1e-10
OUT = Path("reports/carry")


def summary(f8: pd.DataFrame, mask: pd.DataFrame, label: str) -> dict:
    x = f8.where(mask).stack().dropna()
    n = mask.sum(axis=1)
    return {"filter": label, "names_per_window_median": float(n.median()),
            "names_per_window_min": int(n.min()), "names_per_window_max": int(n.max()),
            "distinct_names": int(mask.any().sum()), "name_windows": int(len(x)),
            "below": float((x < DEFAULT - EPS).mean()), "at": float((x - DEFAULT).abs().le(EPS).mean()),
            "above": float((x > DEFAULT + EPS).mean()), "mean_apr": float(x.mean() * WINDOWS_PER_YEAR),
            "median_8h_bp": float(x.median() * 1e4)}


def main(a):
    OUT.mkdir(parents=True, exist_ok=True)
    u = [l.strip() for l in open("data/universe.txt") if l.strip()]
    H = has_spot(u)
    f8 = per_window(load_funding(H, START, END)[H]).loc[a.since:].iloc[:-1]   # last window incomplete

    ap = adv(load_kline_matrix(H, "PERP", "quote_vol", START, END))
    asp = adv(load_kline_matrix(H, "SPOT", "quote_vol", START, END))
    cols = ap.columns.intersection(asp.columns)
    mn = np.minimum(ap[cols], asp[cols]).reindex(f8.index, method="ffill").reindex(columns=f8.columns)
    pit = f8.notna() & (0.02 * mn >= a.clip)

    snap = sorted(Path("data/processed/binance").glob("oi_snapshot_*.csv"))[-1]
    oi = pd.read_csv(snap, index_col=0)
    ok = oi[(0.01 * oi.oi_usd >= a.clip) & (0.02 * oi[["adv_perp_usd_30d", "adv_spot_usd_30d"]].min(axis=1) >= a.clip)].index
    snap_names = [b for b in ok if b in f8.columns]
    sm = f8.notna() & pd.DataFrame(np.broadcast_to(f8.columns.isin(snap_names), f8.shape),
                                    index=f8.index, columns=f8.columns)

    rows = [summary(f8, pit, "point in time: 2% of min ADV >= clip"),
            summary(f8, sm, f"snapshot {snap.stem[-10:]}: 1% OI and 2% min ADV >= clip"),
            summary(f8, f8.notna() & ~pit, "all other hedgeable coins (point in time)")]
    t = pd.DataFrame(rows).set_index("filter")
    freq = pit.mean().sort_values(ascending=False).head(15)
    half = f8.where(pit).mean(axis=1)
    half = half.groupby(half.index.year.astype(str) + "H" + ((half.index.month > 6) + 1).astype(str)).mean() * WINDOWS_PER_YEAR
    per_name = (f8[[b for b in freq.index]].mean() * WINDOWS_PER_YEAR)

    pct = lambda v: f"{v:.1%}"
    L = [f"# Funding in coins that can hold ${a.clip / 1e6:g}m per leg, {f8.index[0].date()} to {f8.index[-1].date()}",
         "", "(autogenerated by scripts/sizable_funding.py; funding only, no costs or basis; default 0.01% per 8h = 10.95% APR)", "",
         t.to_string(formatters={"below": pct, "at": pct, "above": pct, "mean_apr": pct,
                                 "names_per_window_median": "{:.0f}".format, "median_8h_bp": "{:.3f}".format}),
         "", f"Snapshot names: {', '.join(snap_names)}", "",
         "Most frequent point-in-time names (share of windows eligible) and their mean funding APR over the period:",
         pd.DataFrame({"share_eligible": freq.round(2), "mean_apr": per_name.map(pct)}).to_string(), "",
         "Equal-weight point-in-time book, mean funding APR by half-year:",
         half.map(pct).to_string(), ""]
    (OUT / "sizable_funding.md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    ap_ = argparse.ArgumentParser()
    ap_.add_argument("--clip", type=float, default=2.5e6, help="dollars per leg per name")
    ap_.add_argument("--since", default="2025-01-01")
    main(ap_.parse_args())
